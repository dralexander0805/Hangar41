    def _apply_pending_attr(self, directive: str, c: List[str]) -> None:
        attrs = self._pending_attrs

        if directive == "ATTR_draw_disable":
            attrs.draw = False
        elif directive == "ATTR_draw_enable":
            attrs.draw = True
        elif directive == "ATTR_no_cockpit":
            attrs.cockpit_mode = COCKPIT_FEATURE_NONE
            attrs.cockpit_region = 0
            attrs.cockpit_device_args = ()
        elif directive == "ATTR_cockpit":
            attrs.cockpit_mode = PANEL_COCKPIT
            attrs.cockpit_region = 0
            attrs.cockpit_device_args = ()
            self._set_cockpit_panel_mode(PANEL_COCKPIT)
        elif directive == "ATTR_cockpit_lit_only":
            attrs.cockpit_mode = PANEL_COCKPIT_LIT_ONLY
            attrs.cockpit_region = 0
            attrs.cockpit_device_args = ()
            self._set_cockpit_panel_mode(PANEL_COCKPIT_LIT_ONLY)
        elif directive == "ATTR_cockpit_region":
            attrs.cockpit_mode = PANEL_COCKPIT_REGION
            try:
                attrs.cockpit_region = int(c[0])
            except (IndexError, ValueError):
                attrs.cockpit_region = 0
            attrs.cockpit_device_args = ()
            self._set_cockpit_panel_mode(PANEL_COCKPIT_REGION)
        elif directive == "ATTR_cockpit_device":
            attrs.cockpit_mode = COCKPIT_FEATURE_DEVICE
            attrs.cockpit_region = 0
            attrs.cockpit_device_args = tuple(c)
        elif directive == "ATTR_solid_camera":
            attrs.solid_camera = True
        elif directive == "ATTR_no_solid_camera":
            attrs.solid_camera = False
        elif directive == "ATTR_shiny_rat":
            try:
                attrs.shiny_rat = float(c[0])
            except (IndexError, ValueError):
                logger.warn("ATTR_shiny_rat: could not parse value")
                return
            attrs.has_explicit_shiny_rat = True

    def _set_cockpit_panel_mode(self, mode: str) -> None:
        if self._cockpit_panel_mode is None:
            self._cockpit_panel_mode = mode
        elif self._cockpit_panel_mode != mode:
            logger.warn(
                "OBJ uses mixed cockpit panel attribute modes; "
                f"keeping first mode '{self._cockpit_panel_mode}' and importing "
                f"later mode '{mode}' as close as Blender's material model allows"
            )

    def _assign_imported_material(
        self, ob: bpy.types.Object, attrs: Optional[IntermediateAttributes]
    ) -> None:
        mat = self._get_imported_material(attrs or IntermediateAttributes())
        try:
            ob.material_slots[0].material = mat
        except IndexError:
            ob.data.materials.append(mat)

    def _get_imported_material(self, attrs: IntermediateAttributes) -> bpy.types.Material:
        key = attrs.material_key()
        material = self._materials_by_attr_key.get(key)
        if material is not None:
            return material

        material = bpy.data.materials.new(
            f"ImportedMaterial.{len(self._materials_by_attr_key):03}"
        )
        material.use_nodes = True
        material.xplane.draw = attrs.draw
        material.xplane.solid_camera = attrs.solid_camera
        material["xplane_imp_suppress_default_shiny_rat"] = (
            not attrs.has_explicit_shiny_rat
        )

        if attrs.has_explicit_shiny_rat and attrs.shiny_rat is not None:
            material.specular_intensity = attrs.shiny_rat

        if attrs.cockpit_mode == COCKPIT_FEATURE_DEVICE:
            material.xplane.cockpit_feature = COCKPIT_FEATURE_DEVICE
            self._apply_cockpit_device_args(material, attrs.cockpit_device_args)
        elif attrs.cockpit_mode in {
            PANEL_COCKPIT,
            PANEL_COCKPIT_LIT_ONLY,
            PANEL_COCKPIT_REGION,
        }:
            material.xplane.cockpit_feature = COCKPIT_FEATURE_PANEL
            if attrs.cockpit_mode == PANEL_COCKPIT_REGION:
                material.xplane.cockpit_region = str(
                    max(0, min(3, attrs.cockpit_region)) + 1
                )
        else:
            material.xplane.cockpit_feature = COCKPIT_FEATURE_NONE

        self._materials_by_attr_key[key] = material
        return material

    def _apply_cockpit_device_args(
        self, material: bpy.types.Material, args: Tuple[str, ...]
    ) -> None:
        if not args:
            return
        try:
            material.xplane.device_name = args[0]
        except TypeError:
            pass
        try:
            bus_mask = int(args[1], 0)
        except (IndexError, ValueError):
            bus_mask = 0
        for i in range(6):
            try:
                setattr(material.xplane, f"device_bus_{i}", bool(bus_mask & (1 << i)))
            except TypeError:
                pass
        try:
            material.xplane.device_lighting_channel = int(args[2])
        except (IndexError, ValueError):
            pass
        try:
            material.xplane.device_auto_adjust = bool(int(args[3]))
        except (IndexError, ValueError):
            pass

    def _parse_manip_components(
        self, manip_type: str, c: List[str]
    ) -> Optional[IntermediateManipulator]:
        def f(i: int) -> float:
            return float(c[i])

        def s(i: int) -> str:
            return c[i] if i < len(c) else ""

        def tail(start: int) -> str:
            return " ".join(c[start:]) if start < len(c) else ""

        m = IntermediateManipulator(manip_type=manip_type)
        try:
            if manip_type == MANIP_DRAG_XY:
                m.cursor = s(0)
                m.dx = f(1)
                m.dy = f(2)
                m.v1_min = f(3)
                m.v1_max = f(4)
                m.v2_min = f(5)
                m.v2_max = f(6)
                m.dataref1 = s(7)
                m.dataref2 = s(8)
                m.tooltip = tail(9)
            elif manip_type == MANIP_DRAG_AXIS:
                m.cursor = s(0)
                m.dx = f(1)
                m.dy = f(2)
                m.dz = f(3)
                m.v1 = f(4)
                m.v2 = f(5)
                m.dataref1 = s(6)
                m.tooltip = tail(7)
            elif manip_type == MANIP_DRAG_AXIS_PIX:
                m.cursor = s(0)
                m.dx = f(1)
                m.step = f(2)
                m.exp = f(3)
                m.v1 = f(4)
                m.v2 = f(5)
                m.dataref1 = s(6)
                m.tooltip = tail(7)
            elif manip_type == MANIP_DRAG_ROTATE:
                m.cursor = s(0)
                m.origin = (f(1), f(2), f(3))
                m.axis = (f(4), f(5), f(6))
                m.angle1 = f(7)
                m.angle2 = f(8)
                m.lift_at_max = f(9)
                m.v1_min = f(10)
                m.v1_max = f(11)
                m.v2_min = f(12)
                m.v2_max = f(13)
                m.dataref1 = s(14)
                m.dataref2 = s(15)
                m.tooltip = tail(16)
            elif manip_type == MANIP_COMMAND:
                m.cursor = s(0)
                m.command = s(1)
                m.tooltip = tail(2)
            elif manip_type == MANIP_COMMAND_AXIS:
                m.cursor = s(0)
                m.dx = f(1)
                m.dy = f(2)
                m.dz = f(3)
                m.positive_command = s(4)
                m.negative_command = s(5)
                m.tooltip = tail(6)
            elif manip_type in {
                MANIP_COMMAND_KNOB,
                MANIP_COMMAND_SWITCH_UP_DOWN,
                MANIP_COMMAND_SWITCH_LEFT_RIGHT,
            }:
                m.cursor = s(0)
                m.positive_command = s(1)
                m.negative_command = s(2)
                m.tooltip = tail(3)
            elif manip_type in {
                MANIP_COMMAND_KNOB2,
                MANIP_COMMAND_SWITCH_UP_DOWN2,
                MANIP_COMMAND_SWITCH_LEFT_RIGHT2,
            }:
                m.cursor = s(0)
                m.command = s(1)
                m.tooltip = tail(2)
            elif manip_type == MANIP_PUSH:
                m.cursor = s(0)
                m.v_down = f(1)
                m.v_up = f(2)
                m.dataref1 = s(3)
                m.tooltip = tail(4)
            elif manip_type == MANIP_RADIO:
                m.cursor = s(0)
                m.v_down = f(1)
                m.dataref1 = s(2)
                m.tooltip = tail(3)
            elif manip_type == MANIP_TOGGLE:
                m.cursor = s(0)
                m.v_on = f(1)
                m.v_off = f(2)
                m.dataref1 = s(3)
                m.tooltip = tail(4)
            elif manip_type in {MANIP_DELTA, MANIP_WRAP}:
                m.cursor = s(0)
                m.v_down = f(1)
                m.v_hold = f(2)
                m.v1_min = f(3)
                m.v1_max = f(4)
                m.dataref1 = s(5)
                m.tooltip = tail(6)
            elif manip_type in {
                MANIP_AXIS_KNOB,
                MANIP_AXIS_SWITCH_UP_DOWN,
                MANIP_AXIS_SWITCH_LEFT_RIGHT,
            }:
                m.cursor = s(0)
                m.v1 = f(1)
                m.v2 = f(2)
                m.click_step = f(3)
                m.hold_step = f(4)
                m.dataref1 = s(5)
                m.tooltip = tail(6)
            elif manip_type == MANIP_NOOP:
                m.dataref1 = s(0)
                m.tooltip = tail(1)
            else:
                logger.warn(f"Unknown manipulator type: ATTR_manip_{manip_type}")
                return None
        except (IndexError, ValueError) as e:
            logger.warn(f"Could not parse ATTR_manip_{manip_type}: {e}")
            return None
        return m

    def _apply_manip_to_object(
        self, ob: bpy.types.Object, m: IntermediateManipulator
    ) -> None:
        manip = ob.xplane.manip
        # Only mark as an active manipulator when the OBJ is a cockpit file.
        # Non-cockpit OBJs that contain ATTR_manip_* data still get the manip
        # properties stored (as custom props for drag_rotate etc.) but
        # enabled=True without a cockpit material causes export errors.
        manip.enabled = self.is_cockpit
        manip.autodetect_datarefs = False

        try:
            manip.type = m.manip_type
        except TypeError:
            logger.warn(
                f"Could not set manipulator type '{m.manip_type}' on '{ob.name}'"
                " — verify scene xplane version supports this type"
            )

        if m.cursor:
            try:
                manip.cursor = m.cursor
            except TypeError:
                logger.warn(f"Could not set cursor '{m.cursor}' on '{ob.name}'")

        manip.tooltip = m.tooltip

        for attr in (
            "dx", "dy", "dz", "v1", "v2", "v1_min", "v1_max",
            "v2_min", "v2_max", "v_down", "v_up", "v_hold", "v_on", "v_off",
            "step", "click_step", "hold_step", "exp", "wheel_delta",
        ):
            setattr(manip, attr, getattr(m, attr))

        for attr in ("command", "positive_command", "negative_command", "dataref1", "dataref2"):
            val = getattr(m, attr)
            if val:
                setattr(manip, attr, val)

        for start, end, height in m.axis_detent_ranges:
            r = manip.axis_detent_ranges.add()
            r.start = start
            r.end = end
            r.height = height

        if m.manip_type in (MANIP_DRAG_ROTATE, MANIP_DRAG_ROTATE_DETENT):
            ob["xplane_imp_drag_rotate_origin"] = list(m.origin)
            ob["xplane_imp_drag_rotate_axis"] = list(m.axis)
            ob["xplane_imp_drag_rotate_angle1"] = m.angle1
            ob["xplane_imp_drag_rotate_angle2"] = m.angle2
            ob["xplane_imp_drag_rotate_lift_at_max"] = m.lift_at_max

        if m.has_axis_detented:
            ob["xplane_imp_detent_axis"] = list(m.detent_axis)
            ob["xplane_imp_detent_v1_min"] = m.detent_v1_min
            ob["xplane_imp_detent_v1_max"] = m.detent_v1_max
            if m.detent_dataref:
                ob["xplane_imp_detent_dataref"] = m.detent_dataref

        if m.keyframes:
            ob["xplane_imp_manip_keyframes"] = str(m.keyframes)
