# is_vector_axis_aligned was removed from xplane_helpers in 4.3.x — define locally.
def is_vector_axis_aligned(v) -> bool:
    """Returns True if v is approximately aligned with the X, Y, or Z axis."""
    return sum(1 for c in v if round(abs(c), PRECISION_KEYFRAME) != 0) == 1


