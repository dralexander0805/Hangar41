    def _create_empty(self, info: DatablockInfo) -> bpy.types.Object:
        """
        Creates a Blender EMPTY from a DatablockInfo whose parent_info may contain
        a string parent name (our internal ParentInfo). Resolves the name to a real
        bpy.types.Object and sets ob.parent directly, bypassing the 4.3.x
        ParentInfo assertion that requires an Object at construction time.
        """
        our_parent_info = info.parent_info
        info.parent_info = None  # prevent 4.3.x set_parent call inside create_datablock_empty
        ob = test_creation_helpers.create_datablock_empty(info)
        if our_parent_info and our_parent_info.parent:
            pref = our_parent_info.parent
            parent_ob = bpy.data.objects.get(pref) if isinstance(pref, str) else pref
            if parent_ob:
                ob.parent = parent_ob
        info.parent_info = our_parent_info  # restore for future reads
        return ob

